#!/bin/bash
#
# make-ppd.sh -- generates the PPD files for the HP DesignJet 500 driver.
#
#   ./make-ppd.sh    writes ppd/macos/*.ppd (filter by absolute path under
#                    /Library/Printers) and ppd/linux/*.ppd (filter by bare
#                    name, resolved in CUPS' own filter directory)
#
# The DesignJet 500 came in a 24 inch (C7769B) and a 42 inch (C7770B)
# version; the two PPDs differ only in the maximum media width and the
# page sizes offered.

set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
FILTER_PATH=/Library/Printers/cdnj500/filter/pdftocdnj500

# Printer margins (points). The DesignJet 500 keeps 5 mm at the sides and
# 17 mm at the leading and trailing edge in its normal margin mode.
MARGIN_SIDE=14
MARGIN_END=48

# name|label|width|height   (points)   -- portrait orientation
SIZES_24='
A4|A4|595|842
A3|A3|842|1191
A2|A2|1191|1684
A1|A1|1684|2384
Letter|US Letter|612|792
Legal|US Legal|612|1008
Tabloid|Tabloid / ANSI B (11 x 17 in)|792|1224
AnsiC|ANSI C (17 x 22 in)|1224|1584
AnsiD|ANSI D (22 x 34 in)|1584|2448
ARCHA|ARCH A (9 x 12 in)|648|864
ARCHB|ARCH B (12 x 18 in)|864|1296
ARCHC|ARCH C (18 x 24 in)|1296|1728
ARCHD|ARCH D (24 x 36 in)|1728|2592
'
SIZES_42="$SIZES_24"'
A0|A0|2384|3370
AnsiE|ANSI E (34 x 44 in)|2448|3168
30x42|ARCH E1 (30 x 42 in)|2160|3024
ARCHE|ARCH E (36 x 48 in)|2592|3456
'

emit_ppd() {
    local model=$1 max_width=$2 sizes=$3 pcname=$4
    local line name label w h

    cat <<EOF
*PPD-Adobe: "4.3"
*%
*% HP DesignJet 500 ($model) for macOS
*% Renders through Ghostscript's cdnj500 device (HP PCL3GUI raster).
*% Generated by make-ppd.sh -- edit that script, not this file.
*%
*FormatVersion: "4.3"
*FileVersion: "1.0"
*LanguageVersion: English
*LanguageEncoding: ISOLatin1
*PCFileName: "$pcname"
*Manufacturer: "HP"
*Product: "(HP DesignJet 500)"
*ModelName: "HP DesignJet 500 $model"
*ShortNickName: "HP DesignJet 500 $model"
*NickName: "HP DesignJet 500 $model (PCL3GUI via Ghostscript cdnj500)"
*PSVersion: "(3010.000) 0"
*LanguageLevel: "3"
*ColorDevice: True
*DefaultColorSpace: RGB
*FileSystem: False
*Throughput: "1"
*LandscapeOrientation: Plus90
*TTRasterizer: Type42
*1284DeviceID: "MFG:HP;MDL:DesignJet 500;CMD:PCL3GUI;"
*cupsVersion: 1.4
*cupsManualCopies: True
*cupsLanguages: "en"
*cupsFilter: "application/vnd.cups-pdf 0 $FILTER_PATH"

*% --- Page size -----------------------------------------------------------
*OpenUI *PageSize/Media Size: PickOne
*OrderDependency: 10 AnySetup *PageSize
*DefaultPageSize: A4
EOF
    while IFS='|' read -r name label w h; do
        [ -n "$name" ] || continue
        printf '*PageSize %s/%s: "<</PageSize[%s %s]/ImagingBBox null>>setpagedevice"\n' "$name" "$label" "$w" "$h"
    done <<< "$sizes"
    cat <<EOF
*CloseUI: *PageSize

*OpenUI *PageRegion/Media Size: PickOne
*OrderDependency: 10 AnySetup *PageRegion
*DefaultPageRegion: A4
EOF
    while IFS='|' read -r name label w h; do
        [ -n "$name" ] || continue
        printf '*PageRegion %s/%s: "<</PageSize[%s %s]/ImagingBBox null>>setpagedevice"\n' "$name" "$label" "$w" "$h"
    done <<< "$sizes"
    cat <<EOF
*CloseUI: *PageRegion

*DefaultImageableArea: A4
EOF
    while IFS='|' read -r name label w h; do
        [ -n "$name" ] || continue
        printf '*ImageableArea %s/%s: "%s %s %s %s"\n' "$name" "$label" \
            "$MARGIN_SIDE" "$MARGIN_END" "$((w - MARGIN_SIDE))" "$((h - MARGIN_END))"
    done <<< "$sizes"
    cat <<EOF

*DefaultPaperDimension: A4
EOF
    while IFS='|' read -r name label w h; do
        [ -n "$name" ] || continue
        printf '*PaperDimension %s/%s: "%s %s"\n' "$name" "$label" "$w" "$h"
    done <<< "$sizes"
    cat <<EOF

*% Custom sizes: anything up to the roll width, up to 150 inches long.
*HWMargins: $MARGIN_SIDE $MARGIN_END $MARGIN_SIDE $MARGIN_END
*MaxMediaWidth: "$max_width"
*MaxMediaHeight: "10800"
*CustomPageSize True: "pop pop pop <</PageSize[5 -2 roll]/ImagingBBox null>>setpagedevice"
*ParamCustomPageSize Width: 1 points 72 $max_width
*ParamCustomPageSize Height: 2 points 72 10800
*ParamCustomPageSize WidthOffset: 3 points 0 0
*ParamCustomPageSize HeightOffset: 4 points 0 0
*ParamCustomPageSize Orientation: 5 int 0 3

*% --- Print quality (selects 300 or 600 dpi in the filter) ---------------
*OpenUI *cupsPrintQuality/Print Quality: PickOne
*OrderDependency: 20 AnySetup *cupsPrintQuality
*DefaultcupsPrintQuality: Normal
*cupsPrintQuality Draft/Draft (300 dpi): ""
*cupsPrintQuality Normal/Normal (600 dpi): ""
*cupsPrintQuality High/Best (600 dpi, max detail): ""
*CloseUI: *cupsPrintQuality

*DefaultResolution: 600dpi

*% --- Colour mode ---------------------------------------------------------
*OpenUI *ColorModel/Color Mode: PickOne
*OrderDependency: 20 AnySetup *ColorModel
*DefaultColorModel: RGB
*ColorModel RGB/Color: ""
*ColorModel Gray/Grayscale: ""
*CloseUI: *ColorModel

*% --- Fonts (required by the PPD spec; the filter rasterises everything) --
*DefaultFont: Courier
*Font Courier: Standard "(1.05)" Standard ROM
*Font Courier-Bold: Standard "(1.05)" Standard ROM
*Font Helvetica: Standard "(1.05)" Standard ROM
*Font Helvetica-Bold: Standard "(1.05)" Standard ROM
*Font Times-Roman: Standard "(1.05)" Standard ROM
*Font Times-Bold: Standard "(1.05)" Standard ROM
*Font Symbol: Special "(001.007S)" Special ROM
EOF
}

mkdir -p "$HERE/macos" "$HERE/linux"

FILTER_PATH=/Library/Printers/cdnj500/filter/pdftocdnj500
emit_ppd "24in" 1728 "$SIZES_24" "DNJ50024.PPD" > "$HERE/macos/HP-DesignJet_500-24in.ppd"
emit_ppd "42in" 3024 "$SIZES_42" "DNJ50042.PPD" > "$HERE/macos/HP-DesignJet_500-42in.ppd"

FILTER_PATH=pdftocdnj500
emit_ppd "24in" 1728 "$SIZES_24" "DNJ50024.PPD" > "$HERE/linux/HP-DesignJet_500-24in.ppd"
emit_ppd "42in" 3024 "$SIZES_42" "DNJ50042.PPD" > "$HERE/linux/HP-DesignJet_500-42in.ppd"

echo "wrote $HERE/macos/*.ppd and $HERE/linux/*.ppd"
